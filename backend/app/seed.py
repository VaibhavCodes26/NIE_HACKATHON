def seed_database():
    create_tables()

    with SessionLocal() as db:
        # Add missing destinations without duplicating existing records.
        for item in DESTINATIONS:
            existing = db.get(Destination, item["id"])

            if existing is None:
                db.add(Destination(**item))

        db.flush()

        # Avoid duplicating starter attractions when the script is rerun.
        for item in ATTRACTIONS:
            existing = db.scalar(
                select(Attraction).where(
                    Attraction.destination_id == item["destination_id"],
                    Attraction.name == item["name"],
                )
            )

            if existing is None:
                db.add(
                    Attraction(
                        **item,
                        source_status="needs_verification",
                    )
                )

        db.commit()

        destination_count = len(
            db.scalars(select(Destination)).all()
        )
        attraction_count = len(
            db.scalars(select(Attraction)).all()
        )

        print("Database seeded successfully!")
        print(f"Destinations: {destination_count}")
        print(f"Attractions: {attraction_count}")


if __name__ == "__main__":
    seed_database()


